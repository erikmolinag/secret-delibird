/**
 * Sprites de entrenador (Pokemon Showdown). Son la foto del perfil: una por
 * persona, la misma en todos los intercambios. El Pokemon de cada evento vive
 * aparte, en lib/pokemon.ts.
 *
 * Showdown hospeda unos 1,500 archivos, pero la mayoria son el mismo personaje
 * redibujado al estilo de una generacion vieja (`-gen3`, `-gen4dp`) o con el
 * arte de Pokemon Masters, que no pega con el resto. Aqui va la seleccion de
 * los que tienen nombre limpio, agrupados para que se puedan encontrar.
 *
 * El orden importa: los grupos se arman con los que van seguidos.
 */

export type Entrenador = {
  clave: string;
  nombre: string;
  grupo: string;
};

function grupo(etiqueta: string, entradas: [string, string][]): Entrenador[] {
  return entradas.map(([clave, nombre]) => ({ clave, nombre, grupo: etiqueta }));
}

